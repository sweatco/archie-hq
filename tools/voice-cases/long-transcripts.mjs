/**
 * Long-transcript fixtures — the hour-or-two-of-meeting case, and the only fixtures in this harness that measure it.
 *
 * Other transcripts in `dcases.mjs`/`tcases.mjs` hold 10-30 lines (the old three-minute speaking window); it's now the whole meeting, with a three-hour backstop (`TRANSCRIPT_WINDOW_MS` in `meeting.ts`) — 8,000-10,400 tokens/hour, worst case ~40k against the narrowest provider's 131,072-token window, so the rest of the suite measures only the short case.
 *
 * These fixtures are one hour of that, not three: ~9.5k tokens English, ~10.1k Russian — the length a meeting reaches routinely, not its ceiling.
 *
 * The risk: more context can make a model worse at finding a present answer, depending on where it sits (Liu et al., "Lost in the Middle") — out of reach at this suite's old ~3.8k tokens, in reach here. So length and position are different measurements; only a triple — same filler, line at the start, middle, and end — tells them apart.
 *
 * One filler array per language (~500 lines), plus `supplying` and `ask`. A variant splices `supplying` in at one index, appends `ask` last (production always has the addressed turn last) — so the three variants differ only in that index, pure position; long-transcript.test.ts asserts it. `supplying` reads as an aside, splicing naturally anywhere.
 *
 * The filler must stay inert — nothing in it may supply, contradict, or partially satisfy the answer, checked mechanically rather than by reading 500 lines:
 *
 *   - every `must` regex matches the supplying line and nowhere else in the filler or the ask;
 *   - no `BANNED_EN`/`BANNED_RU` term appears outside the supplying line and the ask — wider than `must`, since a filler line volunteering a different owner or blocker would contradict the answer without matching it;
 *   - no identifier from the prompt's worked example appears anywhere, which would disarm `gradeDefect`'s contamination check.
 *
 * Not template-generated — repeating one sentence with numbers changed would measure tolerance for repetition, not meeting behaviour. Both fillers are hand-written instead.
 */

/**
 * Marginal cost in chars/token, fitted not guessed: least-squares of `inputTokens` against length over `results/defect-*.json` (n=120 English, n=60 Russian) gives 3.17 chars/token English, 2.43 Russian — why the fillers differ in length, not lines.
 * Only the marginal rate is kept — the intercept (~3,205 tokens, the prompt's cost when measured) drifts as it's edited (17k characters today vs. 14k then), so every figure here is the transcript's own cost.
 * Pinned as constants, not recomputed from `results/` — gitignored, so a test reading it would pass locally and fail in CI. Tokenizer: Cerebras gemma-4-31b's — treat every figure as an estimate.
 */
export const CHARS_PER_TOKEN = { en: 3.17, ru: 2.43 };

// Rough token count for a transcript, by the fit above. Cyrillic share picks the rate.
export function approxTokens(text) {
  const letters = (text.match(/\p{L}/gu) ?? []).length;
  const cyrillic = (text.match(/[Ѐ-ӿ]/g) ?? []).length;
  const rate = letters > 0 && cyrillic / letters > 0.5 ? CHARS_PER_TOKEN.ru : CHARS_PER_TOKEN.en;
  return Math.round(text.length / rate);
}

