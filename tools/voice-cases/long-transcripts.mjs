// Two groups, one per fact, in the shape `gradeDefect` reads under `kind: 'D4'`.
const EN_MUST = [[/ruslan/i], [/glossar/i]];

// Bounded with (?<!\p{L})/(?!\p{L}) under `u`, never \b — same fix as defect.mjs's MACHINERY_RU. `[а-яё]*`, not `\w*`: `\w` is ASCII-only and would stop at the stem, missing real case endings ("Руслана", "глоссария").
const RU_MUST = [
  [/(?<!\p{L})руслан[а-яё]*(?!\p{L})/iu],
  [/(?<!\p{L})глоссар[а-яё]*(?!\p{L})/iu],
];

// Hand-picked at a natural seam, not computed — a spliced line should not read as a fixture artefact a model could react to. Depths (start within 5%, middle 45-55%, end past 95%, clear of the ask) are asserted in long-transcript.test.ts.
const EN_AT = { start: 7, middle: 241, end: 485 };
const RU_AT = { start: 7, middle: 213, end: 419 };

// Every variant this module builds. `absent` is the same meeting with no answer said — a control kept for the position triple's sake, and what the fixture tests measure the filler against.
export const POSITIONS = ['start', 'middle', 'end', 'absent'];

export const LONG = {
  en: { lang: 'en', filler: EN_FILLER, supplying: EN_SUPPLYING, ask: EN_ASK, must: EN_MUST, banned: BANNED_EN, at: EN_AT },
  ru: { lang: 'ru', filler: RU_FILLER, supplying: RU_SUPPLYING, ask: RU_ASK, must: RU_MUST, banned: BANNED_RU, at: RU_AT },
};

// One variant: filler, plus the supplying line spliced in (or omitted, for `absent`), plus the ask appended last.
export function longTranscript(lang, position) {
  const fixture = LONG[lang];
  if (fixture === undefined) throw new Error(`long-transcripts: unknown language ${lang}`);
  if (!POSITIONS.includes(position)) throw new Error(`long-transcripts: unknown position ${position}`);
  const lines = [...fixture.filler];
  if (position !== 'absent') {
    lines.splice(fixture.at[position], 0, fixture.supplying);
  }
  lines.push(fixture.ask);
  return lines.join('\n');
}

// The filler plus the ask, nothing spliced in — the control the three positions are read against, and what each variant collapses to with its supplying line removed (how the test proves the three differ in exactly that line). LONG[lang].filler (no ask) is what `must` is checked against.
export function fillerOnly(lang) {
  return longTranscript(lang, 'absent');
}
